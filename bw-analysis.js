  function esc(t) {
    return (t || '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  }

  function jump(id) {
    active = id;
    if (typeof window.jumpToSent === 'function') window.jumpToSent(id);
    render();
  }

  function render() {
    var b = document.getElementById('secbody');
    if (!b) return;
    css();
    b.innerHTML = '';

    (window.BW_ANALYSIS.sections || []).forEach(function (m) {
      if (m.part) {
        var h = document.createElement('div');
        h.className = 'spart';
        h.textContent = m.name;
        b.appendChild(h);
        return;
      }

      var isOpen = (open === m.name);
      var wrap = document.createElement('div');
      wrap.className = 'chap' + (isOpen ? ' on' : '');

      var pg = m._s ? 'p.' + m._s.pp : '';
      var head = document.createElement('div');
      head.className = 'chead';
      head.innerHTML = '<span class="caret">&#9654;</span>' +
                       '<span class="cname">' + esc(m.name) + '</span>' +
                       '<span class="cpg">' + pg + '</span>';
      head.onclick = function () {
        open = isOpen ? null : m.name;
        if (!isOpen && m._s) { jump(m._s.id); return; }
        render();
      };
      wrap.appendChild(head);

      var body = document.createElement('div');
      body.className = 'cbody';
      if (m.summary) {
        var sm = document.createElement('div');
        sm.className = 'csum';
        sm.textContent = m.summary;
        body.appendChild(sm);
      }

      (m.subs || []).forEach(function (s) {
        var row = document.createElement('div');
        row.className = 'sub' + (s._s && active === s._s.id ? ' on' : '');
        row.innerHTML = (s._s ? '<div class="spg">p.' + s._s.pp + '</div>' : '') +
                        '<div class="sname">' + esc(s.name) + '</div>' +
                        (s.summary ? '<div class="ssum">' + esc(s.summary) + '</div>' : '');
        row.onclick = function (e) {
          e.stopPropagation();
          if (s._s) jump(s._s.id);
        };
        body.appendChild(row);
      });

      wrap.appendChild(body);
      b.appendChild(wrap);
    });
  }

  window.addEventListener('load', function () {
    setTimeout(function () {
      resolve();
      window.renderSectionsDrawer = render;   // replace the built-in renderer
    }, 120);
  });
